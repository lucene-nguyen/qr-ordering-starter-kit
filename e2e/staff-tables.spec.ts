import { expect, test } from "@playwright/test";
import { account, missingAccount, signIn, signOutIfSignedIn } from "./helpers";

// S1 / S1b · Tables (LEARNING-99). Uses table 12 and leaves it closed again.
test.describe("S1 · tables", () => {
  test.afterEach(async ({ page }) => signOutIfSignedIn(page));

  test("the kitchen cannot open the Tables screen", async ({ page }) => {
    const kitchen = account("kitchen");
    test.skip(!kitchen, missingAccount("kitchen"));
    await signIn(page, kitchen!, "/staff/tables");
    await expect(page.getByRole("heading", { name: "Tables are for the cashier and owner" })).toBeVisible();
  });

  test("a cashier lands on Tables, opens a table, sees its PIN and closes it", async ({ page }) => {
    const cashier = account("cashier");
    test.skip(!cashier, missingAccount("cashier"));
    await signIn(page, cashier!);
    await expect(page).toHaveURL(/\/staff\/tables$/);
    await expect(page.getByRole("heading", { name: "Tables", exact: true })).toBeVisible();

    await page.getByRole("link", { name: /^Table 12/ }).click();
    const panel = page.getByRole("region", { name: "Table 12 details" });
    await panel.getByRole("button", { name: "Open session" }).click();

    const pin = panel.getByText(/^\d{4}$/);
    await expect(pin).toBeVisible(); // PIN generated by the database
    await expect(page.getByRole("link", { name: /^Table 12/ })).toContainText("Ordering");
    await expect(panel).toContainText("Waiting for guests to scan");

    // The PIN stays visible for guests who arrive later.
    await page.reload();
    await expect(page.getByRole("region", { name: "Table 12 details" }).getByText(/^\d{4}$/)).toBeVisible();

    await page.getByRole("region", { name: "Table 12 details" }).getByRole("button", { name: "Close session" }).click();
    await expect(page.getByRole("region", { name: "Table 12 details" }).getByRole("button", { name: "Open session" })).toBeVisible();
    await expect(page.getByRole("link", { name: /^Table 12/ })).toContainText("Available");
  });
});
